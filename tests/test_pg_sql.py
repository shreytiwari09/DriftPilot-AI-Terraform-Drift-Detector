def test_an_extra_table_is_dropped_by_undo_and_created_by_codify() -> None:
    live = shop().model_copy(deep=True)
    live.tables.append(
        Table(
            name="notes",
            columns=[
                Column(name="id", type="int4", nullable=False, identity="by default"),
                Column(name="body", type="text"),
            ],
            constraints=[
                Constraint(name="n_pk", kind="primary key", definition="PRIMARY KEY (id)")
            ],
            indexes=[
                Index(name="n_i", definition="CREATE INDEX n_i ON public.notes USING btree (body)")
            ],
            rls_enabled=True,
            comment="it's a note",
        )
    )
    f = one(live)
    assert statements(f, "before")[-1] == "DROP TABLE public.notes;"
    create = statements(f, "after")
    assert create[0] == (
        "CREATE TABLE public.notes (\n"
        "    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n"
        "    body text,\n"
        "    PRIMARY KEY (id)\n);"
    )
    assert "CREATE INDEX ON public.notes USING btree (body);" in create
    assert "ALTER TABLE public.notes ENABLE ROW LEVEL SECURITY;" in create
    assert "COMMENT ON TABLE public.notes IS 'it''s a note';" in create


def test_owner_and_comment_changes() -> None:
    f = one(edit(shop(), "users", lambda t: setattr(t, "owner", "other")))
    assert statements(f, "before") == ["ALTER TABLE public.users OWNER TO app;"]
    g = one(edit(shop(), "users", lambda t: setattr(t, "comment", None)))
    assert statements(g, "before") == ["COMMENT ON TABLE public.users IS 'Application users';"]
    assert statements(g, "after") == ["COMMENT ON TABLE public.users IS NULL;"]


def test_a_missing_table_cannot_be_rebuilt_by_undo() -> None:
    live = shop().model_copy(deep=True)
    live.tables = [t for t in live.tables if t.name != "orders"]
    f = one(live)
    assert statements(f, "before")  # the summary holds enough to rebuild it
    assert statements(f, "after")[-1] == "DROP TABLE public.orders;"


@pytest.mark.parametrize("evil", ["x; DROP TABLE users", "x -- y", "x /* y */", "a\nb"])
def test_an_expression_that_could_end_the_statement_gives_no_sql(evil) -> None:
    f = one(edit(shop(), "orders", lambda t: setattr(t.columns[3], "default", evil)))
    assert statements(f, "after") is None  # codify would copy the text into a migration
    assert migration_sql([f]) is None
    assert statements(f, "before")  # undo writes the migrations' side, which is safe


def test_semicolons_inside_quotes_are_fine() -> None:
    f = one(edit(shop(), "orders", lambda t: setattr(t.columns[3], "default", "'a;b'")))
    assert statements(f, "after") == [
        "ALTER TABLE public.orders ALTER COLUMN status SET DEFAULT 'a;b';"
    ]


def test_names_with_odd_characters_are_quoted_not_injected() -> None:
    f = one(
        edit(
            shop(),
            "users",
            lambda t: t.columns.append(Column(name='x"; DROP TABLE users;--', type="text")),
        )
    )
    [add] = statements(f, "after")
    assert add == 'ALTER TABLE public.users ADD COLUMN "x""; DROP TABLE users;--" text;'


def test_undo_script_lists_what_it_cannot_write() -> None:
    f = one(edit(shop(), "orders", lambda t: setattr(t.columns[0], "identity", "always")))
    sql, manual = undo_script([f])
    assert sql == "" and manual == ["postgres.public.orders.id auto"]


def test_migration_sql_has_a_header_and_every_statement() -> None:
    live = edit(shop(), "users", lambda t: t.columns.append(Column(name="nickname", type="text")))
    sql = migration_sql(findings(shop(), live))
    assert sql.startswith("-- Written by DriftPilot")
    assert "mark this migration as applied" in sql
    assert sql.rstrip().endswith("ALTER TABLE public.users ADD COLUMN nickname text;")


def test_migration_sql_is_none_when_one_finding_has_no_sql() -> None:
    f = one(edit(shop(), "orders", lambda t: setattr(t.columns[0], "identity", "always")))
    assert migration_sql([f]) is None
    assert migration_sql([]) is None
