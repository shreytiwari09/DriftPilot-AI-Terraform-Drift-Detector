"""Plain SQL for a finding: to undo it on the live database, or to codify it in a migration.

Deterministic and never run by DriftPilot: it ends up in an issue ("review before running") or in
a migration file in a pull request. Anything it cannot write safely gives `None`.
"""

import re
from typing import Any, Literal

from driftpilot.database.catalog import named_index
from driftpilot.models import DriftFinding

Target = Literal["before", "after"]  # which side the SQL should make true

_SIMPLE = re.compile(r"^[a-z_][a-z0-9_$]*$")
_RESERVED_WORDS = (
    "all analyse analyze and any array as asc both case cast check collate column constraint "
    "create "
    "current_date current_time current_timestamp current_user default desc distinct do else end "
    "except false fetch for foreign from grant group having in initially intersect into leading "
    "limit localtime localtimestamp not null offset on only or order placing primary references "
    "returning select session_user some symmetric table then to trailing true union unique user "
    "using variadic when where window with"
)
_RESERVED = frozenset(re.findall(r"\w+", _RESERVED_WORDS))
_QUOTED = re.compile(r"'(?:[^']|'')*'|\"(?:[^\"]|\"\")*\"")


class Unsafe(ValueError):
    """A value that cannot be put into SQL without risk (it would end or comment the statement)."""


def qi(name: str) -> str:
    """An identifier, quoted when it needs it."""
    if _SIMPLE.match(name) and name not in _RESERVED:
        return name
    return '"' + name.replace('"', '""') + '"'


def ql(text: str | None) -> str:
    """A string literal (or NULL)."""
    return "NULL" if text is None else "'" + text.replace("'", "''") + "'"


def _fragment(text: str) -> str:
    """A type or expression read from the database, checked so it cannot end the statement."""
    rest = _QUOTED.sub("", text)
    if ";" in rest or "--" in rest or "/*" in rest or "\n" in rest:
        raise Unsafe(text[:40])
    return text


def _role(name: str) -> str:
    return "PUBLIC" if name.upper() == "PUBLIC" else qi(name)


def split_address(f: DriftFinding) -> tuple[str, str, str | None]:
    """(schema, table, column) of a finding's address, e.g. postgres.public.users.email."""
    parts = f.address.split(".")[1:]
    if f.resource_type == "pg_column":
        return parts[0], ".".join(parts[1:-1]), parts[-1]
    return parts[0], ".".join(parts[1:]), None


def _table(schema: str, table: str) -> str:
    return f"{qi(schema)}.{qi(table)}"


def column_definition(name: str, spec: dict[str, Any]) -> str:
    """`name type [GENERATED ... AS IDENTITY] [DEFAULT x] [NOT NULL]` from a column summary."""
    text = f"{qi(name)} {_fragment(spec['type'])}"
    if spec.get("generated"):
        text += f" GENERATED ALWAYS AS ({_fragment(spec['generated'])}) STORED"
    elif spec.get("identity"):
        text += f" GENERATED {spec['identity'].upper()} AS IDENTITY"
    elif spec.get("serial"):
        text += " GENERATED BY DEFAULT AS IDENTITY"
    elif spec.get("default") is not None:
        text += f" DEFAULT {_fragment(spec['default'])}"
    return text + ("" if spec.get("nullable", True) else " NOT NULL")


def create_table(schema: str, table: str, spec: dict[str, Any]) -> list[str]:
    parts = [column_definition(n, c) for n, c in spec.get("columns", {}).items()]
    parts += [_fragment(c) for c in spec.get("constraints", [])]
    name = _table(schema, table)
    out = ["CREATE TABLE " + name + " (\n    " + ",\n    ".join(parts) + "\n);"]
    for definition in spec.get("indexes", []):
        out.append(_fragment(definition) + ";")
    if spec.get("row_level_security"):
        out.append(f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY;")
    if spec.get("comment"):
        out.append(f"COMMENT ON TABLE {name} IS {ql(spec['comment'])};")
    for column, c in spec.get("columns", {}).items():
        if c.get("comment"):
            out.append(f"COMMENT ON COLUMN {name}.{qi(column)} IS {ql(c['comment'])};")
    return out


def create_policy(schema: str, table: str, name: str, spec: dict[str, Any]) -> str:
    text = f"CREATE POLICY {qi(name)} ON {_table(schema, table)}"
    if not spec.get("permissive", True):
        text += " AS RESTRICTIVE"
    text += f" FOR {spec.get('command', 'ALL')}"
    text += " TO " + ", ".join(_role(r) for r in spec.get("roles", ["public"]))
    if spec.get("using") is not None:
        text += f" USING ({_fragment(spec['using'])})"
    if spec.get("with_check") is not None:
        text += f" WITH CHECK ({_fragment(spec['with_check'])})"
    return text + ";"


def _alter_policy(schema: str, table: str, name: str, spec: dict[str, Any]) -> str:
    text = f"ALTER POLICY {qi(name)} ON {_table(schema, table)}"
    text += " TO " + ", ".join(_role(r) for r in spec.get("roles", ["public"]))
    if spec.get("using") is not None:
        text += f" USING ({_fragment(spec['using'])})"
    if spec.get("with_check") is not None:
        text += f" WITH CHECK ({_fragment(spec['with_check'])})"
    return text + ";"


def _statements(f: DriftFinding, src: Any, dst: Any) -> list[str] | None:
    """SQL that turns `src` (what the database has now) into `dst` (what it should have)."""
    schema, table, column = split_address(f)
    t = _table(schema, table)
    col = qi(column or "")
    attr = f.attribute_path or ""
    rtype = f.resource_type

    if rtype == "pg_table_rls":
        keyword = "ROW LEVEL SECURITY"
        if attr == "row_level_security":
            return [f"ALTER TABLE {t} {'ENABLE' if dst else 'DISABLE'} {keyword};"]
        if attr == "force_row_level_security":
            return [f"ALTER TABLE {t} {'FORCE' if dst else 'NO FORCE'} {keyword};"]
    elif rtype == "pg_table":
        if attr == "":
            if dst is None:
                return ["-- This deletes the table and all its rows.", f"DROP TABLE {t};"]
            return create_table(schema, table, dst) if src is None else None
        if attr == "owner" and dst:
            return [f"ALTER TABLE {t} OWNER TO {qi(dst)};"]
        if attr == "comment":
            return [f"COMMENT ON TABLE {t} IS {ql(dst)};"]
    elif rtype == "pg_column":
        if attr == "":
            if dst is None:
                return [
                    "-- This deletes the column and the data in it.",
                    f"ALTER TABLE {t} DROP COLUMN {col};",
                ]
            return [f"ALTER TABLE {t} ADD COLUMN {column_definition(column or '', dst)};"]
        if attr == "type":
            cast = _fragment(dst)
            return [f"ALTER TABLE {t} ALTER COLUMN {col} TYPE {cast} USING {col}::{cast};"]
        if attr == "nullable":
            verb = "DROP NOT NULL" if dst else "SET NOT NULL"
            note = (
                []
                if dst
                else ["-- Fails while rows hold NULL in this column: fix those rows first."]
            )
            return [*note, f"ALTER TABLE {t} ALTER COLUMN {col} {verb};"]
        if attr == "default":
            action = "DROP DEFAULT" if dst is None else f"SET DEFAULT {_fragment(dst)}"
            return [f"ALTER TABLE {t} ALTER COLUMN {col} {action};"]
        if attr == "comment":
            return [f"COMMENT ON COLUMN {t}.{col} IS {ql(dst)};"]
    elif rtype == "pg_constraint":
        if dst is not None:
            return [
                f"ALTER TABLE {t} ADD CONSTRAINT {qi(dst['name'])} {_fragment(dst['definition'])};"
            ]
        return [f"ALTER TABLE {t} DROP CONSTRAINT {qi(src['name'])};"]
    elif rtype == "pg_index":
        if dst is not None:
            return [named_index(qi(dst["name"]), _fragment(dst["definition"])) + ";"]
        return [f"DROP INDEX {qi(schema)}.{qi(src['name'])};"]
    elif rtype == "pg_policy":
        name = attr.removeprefix("policy:")
        if dst is None:
            return [f"DROP POLICY {qi(name)} ON {t};"]
        if src is None:
            return [create_policy(schema, table, name, dst)]
        if (src.get("command"), src.get("permissive")) == (
            dst.get("command"),
            dst.get("permissive"),
        ):
            return [_alter_policy(schema, table, name, dst)]
        return [f"DROP POLICY {qi(name)} ON {t};", create_policy(schema, table, name, dst)]
    elif rtype == "pg_grant":
        spec = dst or src
        privilege, role = spec["privilege"], _role(spec["grantee"])
        if dst is not None:
            return [f"GRANT {privilege} ON TABLE {t} TO {role};"]
        return [f"REVOKE {privilege} ON TABLE {t} FROM {role};"]
    return None


def statements(f: DriftFinding, target: Target) -> list[str] | None:
    """SQL that makes the live database match the migrations (`before`), or the other way round."""
    src, dst = (f.after, f.before) if target == "before" else (f.before, f.after)
    try:
        return _statements(f, src, dst)
    except (Unsafe, KeyError, TypeError):
        return None


def undo_script(findings: list[DriftFinding]) -> tuple[str, list[str]]:
    """(SQL that undoes the findings on the live database, findings it cannot write SQL for)."""
    lines: list[str] = []
    manual: list[str] = []
    for f in findings:
        found = statements(f, "before")
        if found is None:
            manual.append(f"{f.address} {f.attribute_path or ''}".strip())
        else:
            lines += found
    return "\n".join(lines), manual


MIGRATION_HEADER = (
    "-- Written by DriftPilot: brings the migrations in line with a change made directly on\n"
    "-- the live database. The live database already has it, so mark this migration as applied\n"
    "-- there instead of running it."
)


def migration_sql(findings: list[DriftFinding]) -> str | None:
    """A migration that adds the findings' live state to the migrations (None if any is unknown)."""
    lines: list[str] = []
    for f in findings:
        found = statements(f, "after")
        if found is None:
            return None
        lines += found
    return MIGRATION_HEADER + "\n\n" + "\n".join(lines) + "\n" if lines else None
